"""Verify the shared wire-format vectors in vectors/vectors.json.

Mirrors crates/lattice-proto/tests/vectors.rs. The vectors are generated by
the Rust implementation and serve as a cross-language regression anchor.
"""

import json
from pathlib import Path

import pytest

from lattice import objects, wire

VECTORS = Path(__file__).resolve().parents[3] / "vectors" / "vectors.json"

FRAME_TYPES = {
    40: "init",
    41: "cookie",
    42: "resp",
    50: "offer",
    51: "custody",
    20: "reconcile",
    21: "want",
    22: "records",
    23: "wary",
    60: "ping",
    61: "dummy",
    62: "attest",
}


def load_vectors():
    with open(VECTORS) as f:
        return json.load(f)


def check_key_event(v, raw):
    ev = objects.parse_key_event(raw)
    assert ev.seq == v["expect"]["seq"]
    if "commitment" in v["expect"]:
        assert ev.commitment().hex() == v["expect"]["commitment"]
    if "prev" in v["expect"]:
        assert ev.prev.hex() == v["expect"]["prev"]
    assert ev.verify_signature(), "key event signature invalid"
    assert ev.encode() == raw, "re-encode mismatch"


def check_record(v, raw):
    rec = objects.parse_record(raw, now=v["now"])
    assert rec.id.hex() == v["expect"]["id"]
    assert rec.seq == v["expect"]["seq"]
    assert rec.mode == v["expect"]["mode"]
    assert rec.scope == v["expect"]["scope"]
    # Re-encode: unsigned + sig + channel_sig.
    obj = rec.unsigned_value()
    obj[14] = rec.sig
    obj[15] = rec.channel_sig
    assert wire.encode(obj) == raw, "re-encode mismatch"


def check_frame(v, raw):
    obj = wire.decode(raw)
    assert isinstance(obj, dict)
    ftype = FRAME_TYPES.get(obj[0])
    assert ftype == v["expect"]["type"], f"frame type {obj.get(0)} != {v['expect']['type']}"
    assert wire.encode(obj) == raw, "re-encode mismatch"


def check_message(v, raw):
    msg = objects.parse_message(raw, now=v["now"])
    assert len(raw) == v["expect"]["bucket"]
    assert msg.leg.hex() == v["expect"]["leg"]
    assert msg.dst.hex() == v["expect"]["dst"]
    env = objects.open_envelope(msg, bytes.fromhex(v["expect"]["recipient_seed"]))
    assert env.kind == objects.KIND_MESSAGE
    assert env.body == v["expect"]["body_utf8"].encode()
    assert env.from_.hex() == v["expect"]["sender"]
    assert objects.verify_envelope_signature(env, msg.raw_header, env.from_)


CHECKS = {
    "key_event": check_key_event,
    "peer_record": check_record,
    "frame": check_frame,
    "message": check_message,
}


@pytest.mark.parametrize("vector", load_vectors(), ids=lambda v: v["name"])
def test_vector(vector):
    raw = bytes.fromhex(vector["hex"])
    CHECKS[vector["kind"]](vector, raw)


@pytest.mark.parametrize("vector", load_vectors(), ids=lambda v: v["name"])
def test_single_byte_flips_are_rejected(vector):
    # Mirror of the Rust single-byte-flip test: every single-byte corruption
    # of a signed object must be rejected. Frames are covered by the Rust
    # suite; here we cover the signed objects.
    kind = vector["kind"]
    if kind not in ("key_event", "peer_record", "message"):
        pytest.skip("frames are covered by the Rust suite")
    raw = bytes.fromhex(vector["hex"])
    now = vector.get("now")
    for i in range(len(raw)):
        bad = bytearray(raw)
        bad[i] ^= 0x01
        bad = bytes(bad)
        try:
            if kind == "key_event":
                ev = objects.parse_key_event(bad)
                assert ev.verify_signature(), "corrupted key event accepted"
            elif kind == "peer_record":
                objects.parse_record(bad, now=now)
            else:  # message
                msg = objects.parse_message(bad, now=now)
                env = objects.open_envelope(
                    msg, bytes.fromhex(vector["expect"]["recipient_seed"])
                )
                assert objects.verify_envelope_signature(
                    env, msg.raw_header, env.from_
                ), "corrupted message accepted"
        except Exception:
            continue  # rejected, as required
        else:
            pytest.fail(f"{vector['name']}: single-byte flip at offset {i} was accepted")
